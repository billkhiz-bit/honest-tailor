"""Measure what check_cv catches and what it misses.

Each case in cases.jsonl is a CV fragment written from the fictional persona in persona/. Fabricated
fragments should be flagged; clean ones should pass. Some categories (misattributed numbers, semantic
inflation) are there because a mechanical checker is expected to miss them: the point is to publish the
real catch rate, not a flattering one.

Usage: python benchmark/run_benchmark.py [--write]   (--write saves the tables to benchmark/RESULTS.md)
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "scripts"))
import check_cv  # noqa: E402

PERSONA = [HERE / "persona" / "master-cv.md", HERE / "persona" / "career-facts.md"]
CASES = HERE / "cases.jsonl"
RESULTS = HERE / "RESULTS.md"


def load_cases(path: Path = CASES) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def run(cases: list[dict]) -> list[dict]:
    sources = check_cv.load_sources(PERSONA)
    results = []
    for case in cases:
        findings = check_cv.check_cv(case["cv"], sources)
        flagged = bool(findings)
        results.append({**case, "flagged": flagged, "correct": flagged == (case["expect"] == "flag"),
                        "findings": [f"{f.kind}: {f.term}" for f in findings]})
    return results


def report(results: list[dict]) -> str:
    by_category = defaultdict(list)
    for r in results:
        by_category[r["category"]].append(r)
    rows = ["| Category | Expected | Cases | Flagged | Correct |", "|---|---|---|---|---|"]
    for category, items in by_category.items():
        expect = items[0]["expect"]
        rows.append(f"| {category} | {expect} | {len(items)} | {sum(r['flagged'] for r in items)} | "
                    f"{sum(r['correct'] for r in items)}/{len(items)} |")
    fabricated = [r for r in results if r["expect"] == "flag"]
    clean = [r for r in results if r["expect"] == "pass"]
    caught = sum(r["flagged"] for r in fabricated)
    false_alarms = sum(r["flagged"] for r in clean)
    summary = (f"**Caught {caught} of {len(fabricated)} fabrications ({caught / len(fabricated):.0%}).** "
               f"Flagged {false_alarms} of {len(clean)} clean fragments (false alarms).")
    wrong = [f"- `{r['id']}` ({r['category']}): {'missed' if r['expect'] == 'flag' else 'false alarm'}. "
             f"{r['note']}" + (f" Flags: {', '.join(r['findings'])}" if r["findings"] else "")
             for r in results if not r["correct"]]
    return "\n".join([summary, "", *rows, "", "## Wrong answers", "", *(wrong or ["None."])]) + "\n"


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description="Measure what check_cv catches and what it misses.")
    ap.add_argument("--write", action="store_true", help="save the tables to benchmark/RESULTS.md")
    args = ap.parse_args()
    try:
        text = report(run(load_cases()))
    except NotImplementedError as e:
        print(f"Cannot run yet: {e}")
        return 2
    print(text)
    if args.write:
        RESULTS.write_text("# Benchmark results\n\nGenerated by `python benchmark/run_benchmark.py --write`.\n\n"
                           + text, encoding="utf-8")
        print(f"Saved {RESULTS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
